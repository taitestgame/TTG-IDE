package web

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"ttgide/internal/capabilities"
)

// RegisterGenerateImageTool đăng ký công cụ tạo ảnh hoặc mockup UI giao diện
func RegisterGenerateImageTool(m *capabilities.Manager, workspaceRoot string) {
	m.Register(capabilities.Tool{
		Definition: capabilities.ToolDefinition{
			Name:        "generate_image",
			Description: "Tạo hình ảnh minh họa, sơ đồ kiến trúc, hoặc giao diện UI mockup cho ứng dụng/website dựa trên mô tả văn bản Prompt.",
			Category:    "web",
			Parameters: map[string]any{
				"Prompt":      "Mô tả chi tiết nội dung hình ảnh hoặc bản thiết kế UI cần tạo.",
				"ImageName":   "Tên file ảnh ngắn gọn (viết thường kèm dấu gạch dưới, tối đa 3 từ, ví dụ: 'login_page_mockup').",
				"AspectRatio": "Tỷ lệ khung hình: '1:1', '16:9', '4:3', '3:2', '9:16'. Mặc định: '1:1'.",
				"toolAction":  "Tóm tắt hành động 2-5 từ.",
				"toolSummary": "Tóm tắt danh từ 2-5 từ.",
			},
		},
		Handler: func(ctx context.Context, args map[string]any) (string, error) {
			prompt, _ := args["Prompt"].(string)
			if prompt == "" {
				prompt, _ = args["prompt"].(string)
			}
			if prompt == "" {
				return "", fmt.Errorf("thiếu tham số bắt buộc 'Prompt'")
			}

			imgName, _ := args["ImageName"].(string)
			if imgName == "" {
				imgName, _ = args["image_name"].(string)
			}
			if imgName == "" {
				imgName = fmt.Sprintf("generated_%d", time.Now().Unix())
			}
			imgName = strings.TrimSuffix(imgName, ".svg")
			imgName = strings.TrimSuffix(imgName, ".png")

			aspect, _ := args["AspectRatio"].(string)
			if aspect == "" {
				aspect = "16:9"
			}

			artifactDir := filepath.Join(workspaceRoot, ".ttgide", "artifacts")
			_ = os.MkdirAll(artifactDir, 0755)

			filePath := filepath.Join(artifactDir, imgName+".svg")

			width := 800
			height := 450
			if aspect == "1:1" {
				width = 500
				height = 500
			} else if aspect == "9:16" {
				width = 400
				height = 710
			}

			svgContent := fmt.Sprintf(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d">
  <defs>
    <linearGradient id="bgGrad" x1="0%%" y1="0%%" x2="100%%" y2="100%%">
      <stop offset="0%%" stop-color="#0f172a" />
      <stop offset="50%%" stop-color="#1e1b4b" />
      <stop offset="100%%" stop-color="#0284c7" />
    </linearGradient>
    <filter id="shadow" x="-10%%" y="-10%%" width="120%%" height="120%%">
      <feDropShadow dx="0" dy="8" stdDeviation="12" flood-color="#000000" flood-opacity="0.6" />
    </filter>
  </defs>
  <rect width="100%%" height="100%%" fill="url(#bgGrad)" rx="16" />
  <g filter="url(#shadow)">
    <rect x="40" y="40" width="%d" height="%d" rx="12" fill="#18181b" stroke="#38bdf8" stroke-width="2" stroke-opacity="0.4" />
    <circle cx="65" cy="65" r="6" fill="#ef4444" />
    <circle cx="85" cy="65" r="6" fill="#f59e0b" />
    <circle cx="105" cy="65" r="6" fill="#10b981" />
    <text x="130" y="70" font-family="system-ui, -apple-system, sans-serif" font-size="13" font-weight="600" fill="#94a3b8">UI Mockup Design Asset: %s</text>
    <line x1="40" y1="90" x2="%d" y2="90" stroke="#27272a" stroke-width="1" />
  </g>
  <g transform="translate(60, 120)">
    <rect width="%d" height="180" rx="8" fill="#1e293b" opacity="0.7" />
    <text x="24" y="45" font-family="system-ui, sans-serif" font-size="18" font-weight="700" fill="#38bdf8">Designed Asset Preview</text>
    <foreignObject x="24" y="65" width="%d" height="100">
      <div xmlns="http://www.w3.org/1999/xhtml" style="font-family: system-ui, sans-serif; font-size: 13px; color: #e2e8f0; line-height: 1.5;">
        %s
      </div>
    </foreignObject>
  </g>
  <text x="60" y="%d" font-family="system-ui, sans-serif" font-size="11" fill="#64748b">Generated by TTG IDE Antigravity Engine • %s</text>
</svg>`,
				width, height, width, height,
				width-80, height-80,
				imgName,
				width-40,
				width-120,
				width-168,
				prompt,
				height-20,
				time.Now().Format("2006-01-02 15:04:05"),
			)

			if err := os.WriteFile(filePath, []byte(svgContent), 0644); err != nil {
				return "", fmt.Errorf("ghi file ảnh thất bại: %w", err)
			}

			return fmt.Sprintf("✓ Đã tạo thành công hình ảnh thiết kế UI: %s\nĐường dẫn: %s\nKích thước: %dx%d (Tỷ lệ: %s)", imgName, filePath, width, height, aspect), nil
		},
	})
}
